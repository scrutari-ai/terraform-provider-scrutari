package provider

import (
	"context"
	"fmt"

	"github.com/hashicorp/terraform-plugin-framework/datasource"
	"github.com/hashicorp/terraform-plugin-framework/datasource/schema"
	"github.com/hashicorp/terraform-plugin-framework/types"

	// Generated wire DTOs — see `client.go` route comment block for
	// the hybrid-architecture rationale.
	gwclient "github.com/scrutari-ai/terraform-provider-scrutari/internal/client"
)

var (
	_ datasource.DataSource              = &DomainDataSource{}
	_ datasource.DataSourceWithConfigure = &DomainDataSource{}
)

func NewDomainDataSource() datasource.DataSource {
	return &DomainDataSource{}
}

type DomainDataSource struct {
	client *Client
}

type DomainDataSourceModel struct {
	ID               types.Int64  `tfsdk:"id"`
	TenantID         types.String `tfsdk:"tenant_id"`
	Domain           types.String `tfsdk:"domain"`
	VerificationType types.String `tfsdk:"verification_type"`
	ChallengeHost    types.String `tfsdk:"challenge_host"`
	Status           types.String `tfsdk:"status"`
	Attempts         types.Int64  `tfsdk:"attempts"`
	LastError        types.String `tfsdk:"last_error"`
	CreatedAt        types.String `tfsdk:"created_at"`
	UpdatedAt        types.String `tfsdk:"updated_at"`
	VerifiedAt       types.String `tfsdk:"verified_at"`
	ExpiresAt        types.String `tfsdk:"expires_at"`
}

// Local wire DTO removed; the gateway's `DomainResponse` is now
// imported from `gwclient` (regenerated by `make generate`). Worth
// flagging on the contract surface: `expected_value` (the secret
// challenge token) is intentionally OMITTED from the gateway's
// public wire shape — see the gateway-side repo for the
// anti-disclosure rationale. The Terraform data source therefore
// cannot expose it either, which is the correct outcome for an IaC
// surface (the dashboard remains the single hand-off path for the
// challenge token).

func (d *DomainDataSource) Metadata(_ context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_domain"
}

