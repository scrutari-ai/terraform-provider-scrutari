func (d *DomainDataSource) Configure(_ context.Context, req datasource.ConfigureRequest, resp *datasource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected provider data type",
			fmt.Sprintf("Expected *Client, got %T.", req.ProviderData),
		)
		return
	}
	d.client = c
}

func (d *DomainDataSource) Read(ctx context.Context, req datasource.ReadRequest, resp *datasource.ReadResponse) {
	var config DomainDataSourceModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// The Terraform schema's `id` attribute is `Int64` for forward
	// compatibility (a future gateway-side migration to BIGINT would
	// be transparent to existing state); the gateway emits `id` as
	// `i32`. We pass the int64 through to the URL — `%d` formats both
	// widths cleanly — and cast int32 → int64 at the hydration
	// boundary.
	id := config.ID.ValueInt64()
	var row gwclient.DomainResponse
	if err := d.client.do(ctx, "GET", fmt.Sprintf("/v1/domains/%d", id), nil, &row, ""); err != nil {
		appendAPIErrorDiag(&resp.Diagnostics, "Failed to read domain", err)
		return
	}

	// Field-name notes (oapi-codegen CamelCase, not Go's preferred
	// initialism convention): Id / TenantId / VerificationType /
	// ChallengeHost / LastError / VerifiedAt. `LastError` and
	// `VerifiedAt` are `*string` because the gateway-side Rust types
	// are `Option<String>` (nullable on the wire — see #237's
	// `Option<String>` pattern).
	model := DomainDataSourceModel{
		ID:               types.Int64Value(int64(row.Id)),
		TenantID:         types.StringValue(row.TenantId),
		Domain:           types.StringValue(row.Domain),
		VerificationType: types.StringValue(row.VerificationType),
		ChallengeHost:    types.StringValue(row.ChallengeHost),
		Status:           types.StringValue(row.Status),
		Attempts:         types.Int64Value(int64(row.Attempts)),
		CreatedAt:        types.StringValue(row.CreatedAt),
		UpdatedAt:        types.StringValue(row.UpdatedAt),
		ExpiresAt:        types.StringValue(row.ExpiresAt),
	}
	if row.LastError != nil {
		model.LastError = types.StringValue(*row.LastError)
	} else {
		model.LastError = types.StringNull()
	}
	if row.VerifiedAt != nil {
		model.VerifiedAt = types.StringValue(*row.VerifiedAt)
	} else {
		model.VerifiedAt = types.StringNull()
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, model)...)
}
